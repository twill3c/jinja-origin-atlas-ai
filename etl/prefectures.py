PREF_NAME_CODE: dict[str, str] = {v: k for k, v in PREF_CODE_NAME.items()}

_AREA = re.compile(r"^JP-(\d{2})$")


def code_from_area(area: str) -> str:
    """`JP-13` → `"13"`。表に無ければ例外(全国ファイル `JP` も県を持たない)。"""
    m = _AREA.match(area or "")
    if not m or m.group(1) not in PREF_CODE_NAME:
        raise ValueError(f"都道府県の area ではない: {area!r}")
    return m.group(1)
